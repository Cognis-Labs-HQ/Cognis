/** Keep domain failures actionable without exposing unexpected exception messages. */
export function libraryFailure(error: unknown): {
    code: string;
    status: number;
    conflictEntryId?: string;
} {
    const message = error instanceof Error ? error.message : "";
    const [code, detail] = message.split(":");
    if (!DOMAIN_CODES.has(code)) return { code: "request_failed", status: 500 };
    if (
        code === "content_conflict" &&
        detail &&
        /^[a-zA-Z0-9._-]{1,100}$/.test(detail)
    )
        return { code, status: 409, conflictEntryId: detail };
    if (["forbidden", "entry_not_editable"].includes(code))
        return { code, status: 403 };
    if (["not_found", "entry_not_found"].includes(code))
        return { code, status: 404 };
    if (code.startsWith("jisho_")) return { code, status: 502 };
    return { code, status: 400 };
}
